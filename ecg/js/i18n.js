const dict = { en: { ...en, _m: enMetrics }, hu: { ...hu, _m: huMetrics } };
let lang = localStorage.getItem('ecg.lang') || 'en';

export function getLang() { return lang; }
export function setLang(l) {
  lang = dict[l] ? l : 'en';
  localStorage.setItem('ecg.lang', lang);
  document.documentElement.lang = lang;
  applyI18n();
}
export function t(key) {
  return dict[lang][key] ?? dict.en[key] ?? key;
}
export function metricLabel(key) {
  const m = dict[lang]._m[key] || dict.en._m[key];
  return m ? m[0] : key;
}
export function metricDesc(key) {
  const m = dict[lang]._m[key] || dict.en._m[key];
  return m ? m[1] : '';
}
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.dispatchEvent(new CustomEvent('i18n-changed', { detail: { lang } }));
}
export function fmtNumber(v, dec = 1) {
  if (v === null || v === undefined || Number.isNaN(v) || !Number.isFinite(v)) return t('metricValueNA');
  return v.toLocaleString(lang === 'hu' ? 'hu-HU' : 'en-US', { minimumFractionDigits: dec, maximumFractionDigits: dec });
}
export function fmtDuration(sec) {
  if (!Number.isFinite(sec)) return t('metricValueNA');
  const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = Math.floor(sec % 60);
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
}
export function fmtDateTime(d) {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) return t('metricValueNA');
  return d.toLocaleString(lang === 'hu' ? 'hu-HU' : 'en-GB');
}
export function fmtTime(d) {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) return t('metricValueNA');
  return d.toLocaleTimeString(lang === 'hu' ? 'hu-HU' : 'en-GB');
}
